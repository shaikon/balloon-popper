# Auckland University Electrical Engineering Robotics Association - Undergrad Balloon Popper Competition.
"""
Generate LUA/constants.lua from Companion/constants.py.

WHY THIS EXISTS
  A hand-transcribed constant that differs from its Python source by one digit
  is a real behaviour change, invisible in review, flown without anyone
  choosing it: the Lua would carry a different number than constants.py says.
  At the scale of hundreds of constants that is not a risk, it is a certainty.
  So: generate.  test_lua_deploy.py fails when LUA/constants.lua is not what
  this generates.

WHAT IS EXPORTED
  Module-level ALL_CAPS names bound to int/float/bool.  Nothing else - no
  numpy arrays, no tuples, no derived expressions.  A constant that is not a
  plain scalar is REPORTED, not silently skipped, because a silently missing
  constant becomes a nil in Lua arithmetic and a nil in Lua arithmetic is a
  runtime error that removes the script mid-flight.

BOOLEANS
  Emitted as Lua true/false.  Python's `if C.SOME_FLAG:` and Lua's
  `if C.SOME_FLAG then` agree for booleans, but NOT for 0 - Python treats 0 as
  falsey while Lua treats 0 as TRUE.  Any constant used as a flag but stored as
  an int is therefore flagged in the report so it can be checked by eye.

Run:  python -m Companion.gen_constants
"""

from __future__ import annotations

import ast
import os
from typing import Any


# Modules that hold steering constants.  A constant defined in a module not
# listed here is nil in Lua, and a nil constant is a runtime error that removes
# the script.  If a future module gains constants, add it HERE.
SOURCES = ("Companion.constants",
           "Companion.control_laws")


def collect_one(modname: str) -> tuple[dict[str, Any], list[tuple[str, str]]]:
    """Return ({name: value}, [(name, reason_skipped)]) for one module."""
    import importlib
    mod = importlib.import_module(modname)
    path = mod.__file__

    src = open(path).read()
    tree = ast.parse(src)
    order: list[str] = []
    for node in tree.body:
        targets = []
        if isinstance(node, ast.Assign):
            targets = [t.id for t in node.targets if isinstance(t, ast.Name)]
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            targets = [node.target.id]
        for t in targets:
            if t.isupper() and t not in order:
                order.append(t)

    out: dict[str, Any] = {}
    skipped: list[tuple[str, str]] = []
    for name in order:
        v = getattr(mod, name, None)
        if isinstance(v, bool):
            out[name] = v
        elif isinstance(v, (int, float)):
            # numpy scalars subclass float/int - coerce so repr is clean
            out[name] = v.item() if hasattr(v, "item") else v
        elif isinstance(v, (tuple, list)) and v and all(
                isinstance(e, (int, float)) and not isinstance(e, bool) for e in v):
            # Numeric tuples are emitted as Lua arrays (1-based, which is why
            # every consumer must offset).
            out[name] = tuple(e.item() if hasattr(e, "item") else e for e in v)
        elif v is None:
            skipped.append((name, "None"))
        else:
            skipped.append((name, type(v).__name__))
    return out, skipped


def collect(_path: str = "") -> tuple[dict[str, Any], list[tuple[str, str]]]:
    """Merge every source module.  A name defined in two modules is an ERROR -
    silently preferring one would make the Lua and Python disagree about which
    value is authoritative."""
    merged: dict[str, Any] = {}
    owner: dict[str, str] = {}
    skipped: list[tuple[str, str]] = []
    for m in SOURCES:
        vals, skip = collect_one(m)
        for k, v in vals.items():
            if k in merged and merged[k] != v:
                raise ValueError(
                    f"constant {k} defined differently in {owner[k]} ({merged[k]}) "
                    f"and {m} ({v}) - resolve upstream, do not guess here")
            merged[k] = v
            owner.setdefault(k, m)
        skipped.extend((f"{m.split('.')[-1]}.{n}", why) for n, why in skip)
    return merged, skipped


def render(values: dict[str, Any]) -> str:
    L = [
        "-- Auckland University Electrical Engineering Robotics Association"
        " - Undergrad Balloon Popper Competition.",
        "--",
        "-- GENERATED by Companion/gen_constants.py -- DO NOT EDIT.",
        "--",
        "-- Every value is copied from Companion/constants.py, which is the",
        "-- single source of truth.  Hand-editing a value here makes the Lua",
        "-- path fly a different number than constants.py says, silently.",
        "-- Change constants.py and regenerate.",
        "--",
        "-- Booleans are emitted as Lua true/false.  Beware flags stored as ints:",
        "-- Python treats 0 as falsey, Lua treats 0 as TRUE.  Compare explicitly",
        "-- (`if C.FLAG ~= 0 then`) rather than relying on truthiness.",
        "",
        "local C = {}",
        "",
    ]
    def _num(x):
        """Render a float as LUA source.

        repr() is not enough: Python emits `inf`, `-inf` and `nan`, none of
        which are Lua literals.  `inf` compiles as a GLOBAL READ returning nil,
        so C.POINT_BALLOON_RANGE was nil and every comparison against it was a
        silent no-op - found by luac -l, not by any test that ran the code.
        """
        f = float(x)
        if f != f:
            return "(0/0)"                 # nan
        if f == float("inf"):
            return "math.huge"
        if f == float("-inf"):
            return "-math.huge"
        return repr(f)

    for k, v in values.items():
        if isinstance(v, tuple):
            body = ", ".join(_num(e) if isinstance(e, float) else repr(e)
                             for e in v)
            L.append(f"C.{k} = {{ {body} }}   -- 1-BASED in Lua; Python indexes from 0")
            continue
        if isinstance(v, bool):
            L.append(f"C.{k} = {'true' if v else 'false'}")
        elif isinstance(v, int):
            L.append(f"C.{k} = {v}")
        else:
            L.append(f"C.{k} = {_num(v)}")
    L += ["", "return C", ""]
    return "\n".join(L)


def main() -> int:
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.abspath(os.path.join(here, ".."))
    src = os.path.join(root, "Companion", "constants.py")
    dst = os.path.join(root, "LUA", "constants.lua")

    values, skipped = collect(src)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    open(dst, "w").write(render(values))

    n_tuple = sum(1 for v in values.values() if isinstance(v, tuple))
    n_bool = sum(1 for v in values.values() if isinstance(v, bool))
    n_int = sum(1 for v in values.values()
                if isinstance(v, int) and not isinstance(v, bool)
                and not isinstance(v, tuple))
    n_float = sum(1 for v in values.values() if isinstance(v, float))

    print(f"exported {len(values)} constants -> {dst}")
    print(f"  {n_float} float, {n_int} int, {n_bool} bool, {n_tuple} numeric tuple")
    if skipped:
        print(f"\n  NOT EXPORTED ({len(skipped)}) - not plain scalars.")
        print("  If the steering core needs any of these, it must be handled")
        print("  explicitly; a missing constant becomes nil in Lua arithmetic,")
        print("  which raises and removes the script mid-flight.")
        for n, why in skipped[:20]:
            print(f"    {n:<38} {why}")
        if len(skipped) > 20:
            print(f"    ... and {len(skipped) - 20} more")

    # int-valued flags: the Python-falsey / Lua-truthy trap
    flagish = [k for k, v in values.items()
               if isinstance(v, int) and not isinstance(v, bool) and v in (0, 1)
               and ("ENABLE" in k or "_EN" in k or "MODE" in k or "LAW" in k)]
    if flagish:
        print(f"\n  INT-VALUED FLAGS ({len(flagish)}) - compare explicitly in Lua,")
        print("  `if C.X ~= 0 then`, never `if C.X then` (0 is TRUE in Lua):")
        for k in flagish:
            print(f"    {k} = {values[k]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

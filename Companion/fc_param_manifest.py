"""
fc_param_manifest.py — the frozen inventory of every flight-controller parameter.

Frozen from a KNOWN-GOOD Talon FC (SERVO1_FUNCTION == 4 verified).  Freezing it
from a stale eeprom instead - e.g. a leftover Zephyr servo mapping - would bake
in exactly the broken state the gate exists to detect, so re-freeze only from a
confirmed-good FC (see REGENERATING below).

WHY THIS EXISTS
---------------
A --add-param-file supplies DEFAULTS only, and a default never overrides a value
already stored in eeprom. An airframe can therefore be flown with another
aircraft's servo mapping while every file on disk names the right one.

read_fc_config() reads each parameter and reports mismatches, but a per-parameter
advisory cannot express "this is the wrong aircraft" - it is one line among forty
and nothing stops. Only a gate can refuse.

THE PARAMETER SET IS NOT STATIC
-------------------------------
ArduPilot registers a parameter subtree only when its enabler is non-zero. Four
groups behave this way here: ARSPD_* under ARSPD_TYPE, BATT_* under BATT_MONITOR,
SCR_* under SCR_ENABLE, YAW_RATE_* under YAW_RATE_ENABLE - 57 parameters in
total. The enabler itself always survives; only its children vanish.

This matters because the operator turns some of them on by hand: SCR_ENABLE
and ARSPD_TYPE for the Lua path, YAW_RATE_ENABLE for the rudder.  The frozen
dump was taken with them at their defaults, so their children are absent from
FLIGHT_PARAMS and appear the moment the enabler is set - a flat name list could
not be correct on both sides of that change.

CONDITIONAL_GROUPS models this: a dependent is required only when its enabler is
non-zero, and is never reported as unexpected. FLIGHT_PARAMS holds only the
unconditional names.

THE GATE (verify_param_manifest in adapters/mavlink_link.py)
------------------------------------------------------------
  Stage 1  NAME SET EQUALITY, conditional-aware. Names, not values. Either
           direction ABORTS.
  Stage 2  BUCKET_1_IDENTITY values (servo FUNCTION and REVERSED). ABORTS -
           this is the wrong aircraft.
  Then     BUCKET_1B_OUTPUT_CAL values (servo MIN/MAX/TRIM) and BUCKET_2_*,
           checked READ-ONLY; a difference HALTS for the operator with the
           others at the end of read_fc_config.  Calibration is not identity: a
           trim of 1500 reads the same on any airframe.
  Bucket 3 Recorded, never value-checked. Calibration and tuning numbers are
           SUPPOSED to drift; alarming on them trains the operator to click past
           the alarm that matters.

SIM_* (355 of 1334) exist only under SITL and are never gated, so one manifest
serves both SITL and hardware.

REGENERATING
------------
Firmware upgrades, and deliberate changes to what hardware the FC believes it has,
change the set. Dump `param show *` from a KNOWN-GOOD FC (check SERVO1_FUNCTION
first) and rebuild. Do not silence a Stage 1 failure by deleting names.
"""


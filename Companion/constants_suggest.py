"""constants_suggest - shared writer for suggested_constants_<origin>.py files.

Every writer of a constants.py copy uses it, so the outputs are mechanically
identical and differ only in WHAT they substitute and the filename:

    sweep      ('t')   -> suggested_constants_t.py   (WINNING SET scalar gains)
    cell tune  ('y')   -> suggested_constants_y.py   (WINNING SET scalar gains)
    Gain Tuner (Copy)  -> gui_live_values.py         (every tunable's live value)

The file written is a byte-for-byte copy of the LIVE constants.py (read from
the actually-imported module, so every locally tuned value survives) with ONLY
the named assignments replaced.  A banner records the origin, date, provenance
of every substituted value, anything that could NOT be substituted, and the
exact copy command to apply.  NOTHING is applied automatically - the operator
reviews, copies over constants.py, and restarts.
"""
from __future__ import annotations

import datetime
import os
import re

from . import constants as C
from . import file_export as _fx
from .csv_logger import PACKAGE_SHA256


def _live_constants_source():
    """(abs_path, text) of the live constants.py the running app imported."""
    p = C.__file__
    if p.endswith(('.pyc', '.pyo')):
        p = p[:-1]
    with open(p, encoding='utf-8') as f:
        return os.path.abspath(p), f.read()


def write_suggested_constants(out_name, origin, notes, log,
                              scalar_subs=None, from_run=True, dict_subs=None):
    """Write CWD/<out_name>: live constants.py with the given assignments
    replaced.  scalar_subs: NAME -> python numeric literal string (trailing
    comments on the line are preserved); dict_subs: DICT_NAME -> {key: literal}, each entry
    replaced inside that one dict literal only - the same key in another dict
    (NATIVE_MODE_RATE_PIDS beside EXPECTED_RATE_PIDS) is left alone.  Returns
    the written path, or None when no substitution succeeded.  Never raises for
    a missing name - it is reported in the banner and the log instead."""
    scalar_subs = scalar_subs or {}
    dict_subs = dict_subs or {}
    src_path, text = _live_constants_source()

    # If the live constants.py was itself produced by a previous suggested_
    # constants_*.py or GUI Live Values copy (the designed workflow), it starts
    # with that generation's banner.  Strip any such leading banner(s) so files never stack stale
    # provenance headers - each generated file carries exactly ONE banner: its
    # own.  A stacked stale banner makes a correct sweep output look like an
    # old file.
    _banner_pat = re.compile(
        r'\A# ={74}\n# (?:SUGGESTED CONSTANTS - auto-generated|Copied from ).*?'
        r'\n# ={74}\n\n?', re.S)
    while True:
        text, n = _banner_pat.subn('', text, count=1)
        if not n:
            break

    applied, failed = [], []
    for name, lit in scalar_subs.items():
        pat = re.compile(r'^(%s\s*=\s*)([^#\r\n]*?)(\s*#[^\r\n]*)?$' % re.escape(name), re.M)
        text, n = pat.subn(
            lambda m: m.group(1) + lit + (m.group(3) or ''), text, count=1)
        (applied if n == 1 else failed).append(name)
    for dict_name, entries in dict_subs.items():
        block = re.search(r'^%s\s*=\s*\{\n(.*?)^\}' % re.escape(dict_name),
                          text, re.M | re.S)
        if block is None:
            failed.extend('%s[%s]' % (dict_name, k) for k in entries)
            continue
        body = block.group(1)
        for key, lit in entries.items():
            pat = re.compile(r"^(\s*'%s'\s*:\s*)([^,#\r\n]*?)(\s*,)" % re.escape(key),
                             re.M)
            body, n = pat.subn(lambda m: m.group(1) + lit + m.group(3), body, count=1)
            (applied if n == 1 else failed).append('%s[%s]' % (dict_name, key))
        text = text[:block.start(1)] + body + text[block.end(1):]
    if not applied:
        log.warning('[SUGGEST] no target lines found in %s - %s not written.',
                    src_path, out_name)
        return None

    # The RUN's stamp, read back out of this file's own name, so the header and
    # the filename can never disagree.  An unstamped name (the Gain Tuner's
    # snapshot, which belongs to no run) falls back to the current time.
    _ts = _fx.stamp_from_name(out_name)
    _when = (_fx.stamp_display(_ts) if _ts
             else datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S'))
    banner = [
        '# ' + '=' * 74,
        ('# SUGGESTED CONSTANTS - auto-generated by a %s that started on %s'
         % (origin, _when)) if from_run else
        ('# Copied from %s on %s' % (origin, _when)),
        '# code_sha256: %s' % PACKAGE_SHA256,
        '# This is a copy of your live constants.py (%s)' % src_path,
        '# with ONLY the lines listed below updated.  Every other value is yours,',
        '# untouched.  NOTHING has been applied automatically.',
        '#',
    ] + ['#   - %s' % n for n in notes] + ([
        '#   - could not locate in the file (apply by hand): %s' % ', '.join(failed)]
        if failed else []) + [
        '#',
        '# TO APPLY: review the values, then replace your constants.py with this',
        '# file and restart:',
        '#     cp %s "%s"' % (out_name, src_path),
        '# ' + '=' * 74,
        '',
    ]
    out_path = os.path.join(os.getcwd(), out_name)
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(banner) + text)
    # A completed run's suggested-constants file is KEPT, not claimed away: it
    # carries the run stamp, so a rerun writes a new file beside the old one
    # rather than colliding, and the operator clears them with Delete.  This is
    # the same retention every id/autotune output follows; only the resume
    # checkpoint is cleaned.  (The 'suggested_t'/'suggested_y' exports pick the
    # newest.)
    log.info('[SUGGEST] %s written to %s', out_name, out_path)
    log.info('[SUGGEST]   updated: %s', ', '.join(applied))
    for n in notes:
        log.info('[SUGGEST]   %s', n)
    if failed:
        log.warning('[SUGGEST]   NOT found (apply by hand): %s', ', '.join(failed))
    log.info('[SUGGEST]   TO APPLY (after review):  cp %s "%s"  then restart.',
             out_name, src_path)
    return out_path
